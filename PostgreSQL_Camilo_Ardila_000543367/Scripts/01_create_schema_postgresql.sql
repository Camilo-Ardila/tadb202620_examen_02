-- Cambios de fondo respecto al original en MySQL:
--   - AUTO_INCREMENT -> GENERATED BY DEFAULT AS IDENTITY (se eligió
--     "BY DEFAULT" en vez de "ALWAYS" para permitir inserts con id
--     explícito en el script de carga de datos, si lo necesitan).
--   - ENGINE = InnoDB: no aplica en PostgreSQL, se elimina.
--   - INDEX inline dentro de CREATE TABLE: no existe en PostgreSQL;
--     cada índice se crea como una sentencia CREATE INDEX aparte,
--     después de la tabla correspondiente.
--   - REGEXP_LIKE(...) -> operador ~ (ya es case-sensitive, igual que
--     el flag 'c' del original).
--   - STATS_SAMPLE_PAGES (opción de tabla de MySQL): no existe en
--     PostgreSQL. El equivalente más cercano es correr ANALYZE después
--     de cargar los datos, o ajustar default_statistics_target por
--     columna con ALTER TABLE ... ALTER COLUMN ... SET STATISTICS n.
--     Se deja como comentario al final de la tabla puente.
--   - Todo el bloque de creación de tablas corre con
--     SET ROLE brechas_owner_role, para que las tablas queden con ese
--     rol como dueño (ver script 00) y así brechas_camilo/brechas_david
--     puedan crear índices sobre ellas sin ser superusuarios.
-- =====================================================================


-- Desde PostgreSQL 15, CREATE sobre el esquema "public" ya NO se
-- otorga a PUBLIC por defecto -- solo el dueño del esquema (postgres,
-- quien corrió el CREATE DATABASE en el script 00) puede crear objetos
-- ahí. Sin este GRANT, el SET ROLE de abajo falla con "permission
-- denied for schema public", porque SET ROLE adopta los privilegios
-- del rol destino (brechas_owner_role) y no conserva los de postgres.
GRANT CREATE ON SCHEMA public TO brechas_owner_role;

-- Las tablas quedarán con brechas_owner_role como dueño en vez de
-- postgres, para que camilo/david (miembros de ese rol) puedan crear
-- índices. postgres sigue siendo quien ejecuta el script.
SET ROLE brechas_owner_role;


