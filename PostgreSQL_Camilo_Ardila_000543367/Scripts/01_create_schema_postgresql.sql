-- Tablas creadas (deben ser 10)
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_catalog = 'brechas_seguridad'
ORDER BY table_name;

-- Llaves foráneas (incluidas las dos compuestas de la tabla puente)
-- GROUP_CONCAT (MySQL) -> STRING_AGG (PostgreSQL)
SELECT tc.table_name, tc.constraint_name,
       STRING_AGG(kcu.column_name, ',' ORDER BY kcu.ordinal_position) AS columnas,
       ccu.table_name AS referenced_table_name
FROM information_schema.table_constraints tc
JOIN information_schema.key_column_usage kcu
  ON tc.constraint_name = kcu.constraint_name
JOIN information_schema.constraint_column_usage ccu
  ON tc.constraint_name = ccu.constraint_name
WHERE tc.constraint_type = 'FOREIGN KEY'
GROUP BY tc.table_name, tc.constraint_name, ccu.table_name
ORDER BY tc.table_name, tc.constraint_name;

-- Dueño de cada tabla (debe decir brechas_owner_role en las 10)
SELECT tablename, tableowner
FROM pg_tables
WHERE schemaname = 'public'
ORDER BY tablename;

-- SHOW GRANTS (MySQL) -> consulta sobre information_schema
SELECT grantee, table_name, privilege_type
FROM information_schema.role_table_grants
WHERE grantee IN ('brechas_camilo', 'brechas_david')
ORDER BY grantee, table_name, privilege_type;

